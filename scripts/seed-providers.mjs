#!/usr/bin/env node
/**
 * Emits the SQL that seeds the providers table from supabase/seed/providers.json.
 *
 * It writes SQL to stdout rather than talking to Postgres itself, so seeding
 * needs no database driver and the output can be read before it is run:
 *
 *   npm run db:seed:sql                     # inspect
 *   npm run db:seed                         # apply, via scripts/db-seed.ts
 *
 * Two passes, because canonical_provider_id points at another row in the same
 * table and a single ordered insert would make the seed file's ordering
 * load-bearing.
 *
 * The upsert deliberately splits the columns. Directory fields come from TMDB
 * and are overwritten on every run. Editorial fields - kind, canonical
 * provider, notes - are stream-master's own judgment and are only filled in
 * where the row does not already carry one, so a later refresh from the live
 * directory cannot erase a classification somebody made by hand.
 *
 * Stage 1 makes no TMDB requests. This reads a committed snapshot only.
 */

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const seedPath = join(repoRoot, 'supabase', 'seed', 'providers.json');

const VALID_KINDS = new Set([
  'subscription',
  'live_tv_bundle',
  'channel_reseller',
  'transactional',
  'free_ads',
  'unknown',
]);

/** Single-quoted SQL literal, or NULL. */
function lit(value) {
  if (value === undefined || value === null) return 'NULL';
  return `'${String(value).replace(/'/g, "''")}'`;
}

function num(value) {
  if (value === undefined || value === null) return 'NULL';
  if (!Number.isInteger(value)) throw new Error(`expected an integer, got ${value}`);
  return String(value);
}

function bool(value) {
  return value ? 'TRUE' : 'FALSE';
}

/**
 * The seed SQL, as text. Exported so `scripts/db-seed.ts` can apply it without
 * a second implementation and without a shell pipeline in between.
 */
export function providerSeedSql() {
const seed = JSON.parse(readFileSync(seedPath, 'utf8'));
const providers = seed.providers ?? [];

const seen = new Set();
for (const p of providers) {
  if (!Number.isInteger(p.provider_id)) throw new Error(`provider_id must be an integer: ${JSON.stringify(p)}`);
  if (seen.has(p.provider_id)) throw new Error(`duplicate provider_id ${p.provider_id}`);
  seen.add(p.provider_id);
  if (!p.name) throw new Error(`provider ${p.provider_id} has no name`);
  if (p.kind && !VALID_KINDS.has(p.kind)) throw new Error(`provider ${p.provider_id} has unknown kind ${p.kind}`);
}

for (const p of providers) {
  if (p.canonical_provider_id === undefined || p.canonical_provider_id === null) continue;
  if (p.canonical_provider_id === p.provider_id) {
    throw new Error(`provider ${p.provider_id} is its own canonical provider`);
  }
  if (!seen.has(p.canonical_provider_id)) {
    throw new Error(`provider ${p.provider_id} points at absent canonical ${p.canonical_provider_id}`);
  }
}

const out = [];
out.push('-- Generated by scripts/seed-providers.mjs from supabase/seed/providers.json.');
out.push('-- Do not edit. Edit the JSON and regenerate.');
out.push('');
out.push('BEGIN;');
out.push('');

for (const p of providers) {
  out.push(
    `INSERT INTO providers (provider_id, name, logo_path, display_priority, display_priorities, kind, in_tv_directory, in_movie_directory, notes) VALUES (` +
      [
        num(p.provider_id),
        lit(p.name),
        lit(p.logo_path),
        num(p.display_priority),
        `${lit(JSON.stringify(p.display_priorities ?? {}))}::jsonb`,
        `${lit(p.kind ?? 'unknown')}::provider_kind`,
        bool(p.in_tv_directory),
        bool(p.in_movie_directory),
        lit(p.notes),
      ].join(', ') +
      `)\n  ON CONFLICT (provider_id) DO UPDATE SET\n` +
      `    name = EXCLUDED.name,\n` +
      `    logo_path = COALESCE(EXCLUDED.logo_path, providers.logo_path),\n` +
      `    display_priority = COALESCE(EXCLUDED.display_priority, providers.display_priority),\n` +
      `    display_priorities = CASE WHEN EXCLUDED.display_priorities = '{}'::jsonb THEN providers.display_priorities ELSE EXCLUDED.display_priorities END,\n` +
      `    kind = CASE WHEN providers.kind = 'unknown' THEN EXCLUDED.kind ELSE providers.kind END,\n` +
      `    in_tv_directory = providers.in_tv_directory OR EXCLUDED.in_tv_directory,\n` +
      `    in_movie_directory = providers.in_movie_directory OR EXCLUDED.in_movie_directory,\n` +
      `    notes = COALESCE(providers.notes, EXCLUDED.notes),\n` +
      `    updated_at = now();`,
  );
}

out.push('');
out.push('-- Second pass: variant collapsing, once every row it can point at exists.');
for (const p of providers) {
  if (p.canonical_provider_id === undefined || p.canonical_provider_id === null) continue;
  out.push(
    `UPDATE providers SET canonical_provider_id = ${num(p.canonical_provider_id)}, updated_at = now()\n` +
      ` WHERE provider_id = ${num(p.provider_id)} AND canonical_provider_id IS NULL;`,
  );
}

out.push('');
out.push('COMMIT;');
out.push('');

return out.join('\n');
}

// Printing only when run directly, so importing this module has no side effect.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.stdout.write(providerSeedSql());
}
